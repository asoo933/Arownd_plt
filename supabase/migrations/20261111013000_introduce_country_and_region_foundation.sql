-- Introduce country and administrative-region foundations without changing
-- the existing Algeria wilaya identifiers or enabling additional markets.
-- This migration is additive: existing RPC signatures and wilaya columns remain
-- available during the mobile/API compatibility transition.

begin;

create table public.countries (
  code text primary key,
  name_ar text not null,
  name_en text not null,
  flag_emoji text not null,
  currency_code text not null,
  currency_name_ar text not null,
  currency_name_en text not null,
  calling_code text not null,
  is_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint countries_code_format check (code ~ '^[A-Z]{2}$'),
  constraint countries_currency_code_format check (currency_code ~ '^[A-Z]{3}$'),
  constraint countries_code_currency_key unique (code, currency_code)
);

insert into public.countries (
  code, name_ar, name_en, flag_emoji, currency_code,
  currency_name_ar, currency_name_en, calling_code, is_enabled
) values
  ('DZ', 'الجزائر', 'Algeria', '🇩🇿', 'DZD', 'الدينار الجزائري', 'Algerian dinar', '+213', true),
  ('MA', 'المغرب', 'Morocco', '🇲🇦', 'MAD', 'الدرهم المغربي', 'Moroccan dirham', '+212', false),
  ('EG', 'مصر', 'Egypt', '🇪🇬', 'EGP', 'الجنيه المصري', 'Egyptian pound', '+20', false),
  ('SA', 'السعودية', 'Saudi Arabia', '🇸🇦', 'SAR', 'الريال السعودي', 'Saudi riyal', '+966', false),
  ('AE', 'الإمارات', 'United Arab Emirates', '🇦🇪', 'AED', 'الدرهم الإماراتي', 'UAE dirham', '+971', false);

create table public.country_regions (
  id bigint generated by default as identity primary key,
  country_code text not null references public.countries(code) on delete restrict,
  parent_id bigint,
  code text not null,
  name_ar text not null,
  name_fr text,
  name_en text,
  region_type text not null,
  legacy_wilaya_id integer unique references public.wilayas(id) on delete restrict,
  is_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint country_regions_parent_fkey
    foreign key (country_code, parent_id)
    references public.country_regions(country_code, id)
    on delete restrict,
  constraint country_regions_code_nonempty check (length(btrim(code)) > 0),
  constraint country_regions_type_nonempty check (length(btrim(region_type)) > 0),
  constraint country_regions_country_code_key unique (country_code, code),
  constraint country_regions_country_id_key unique (country_code, id)
);

-- Reuse the existing authoritative 58-wilaya dataset. Preserve French source
-- names as French; English translations remain NULL until verified translations exist.
insert into public.country_regions (
  country_code, code, name_ar, name_fr, region_type, legacy_wilaya_id
)
select
  'DZ',
  lpad(w.id::text, 2, '0'),
  w.name_ar,
  w.name_fr,
  'wilaya',
  w.id
from public.wilayas w
on conflict (country_code, code) do nothing;

-- Country is explicit on each market-owned record. DZ defaults preserve
-- compatibility with existing Algeria-only clients and RPCs during rollout.
alter table public.profiles
  add column country_code text not null default 'DZ'
  references public.countries(code) on delete restrict,
  add column region_id bigint;

alter table public.stores
  add column country_code text not null default 'DZ'
  references public.countries(code) on delete restrict,
  add column region_id bigint;

alter table public.orders
  add column country_code text not null default 'DZ'
  references public.countries(code) on delete restrict,
  add column region_id bigint,
  add column currency_code text not null default 'DZD';

alter table public.user_addresses
  add column country_code text not null default 'DZ'
  references public.countries(code) on delete restrict,
  add column region_id bigint;

-- Backfill references while retaining every legacy wilaya_id value.
update public.profiles p
set region_id = r.id
from public.country_regions r
where r.country_code = p.country_code
  and r.legacy_wilaya_id = p.wilaya_id;

update public.stores s
set region_id = r.id
from public.country_regions r
where r.country_code = s.country_code
  and r.legacy_wilaya_id = s.wilaya_id;

update public.orders o
set region_id = r.id
from public.country_regions r
where r.country_code = o.country_code
  and r.legacy_wilaya_id = o.wilaya_id;

update public.user_addresses a
set region_id = r.id
from public.country_regions r
where r.country_code = a.country_code
  and r.legacy_wilaya_id = a.wilaya_id;

-- Enforce that a selected region belongs to the same country as its record.
alter table public.profiles
  add constraint profiles_country_region_fkey
  foreign key (country_code, region_id)
  references public.country_regions(country_code, id)
  on delete restrict;

alter table public.stores
  add constraint stores_country_region_fkey
  foreign key (country_code, region_id)
  references public.country_regions(country_code, id)
  on delete restrict;

alter table public.orders
  add constraint orders_country_region_fkey
  foreign key (country_code, region_id)
  references public.country_regions(country_code, id)
  on delete restrict,
  add constraint orders_country_currency_fkey
  foreign key (country_code, currency_code)
  references public.countries(code, currency_code)
  on delete restrict;

alter table public.user_addresses
  add constraint user_addresses_country_region_fkey
  foreign key (country_code, region_id)
  references public.country_regions(country_code, id)
  on delete restrict;

create index profiles_country_region_idx
  on public.profiles (country_code, region_id);

create index stores_country_region_idx
  on public.stores (country_code, region_id);

create index orders_country_region_idx
  on public.orders (country_code, region_id);

create index user_addresses_country_region_idx
  on public.user_addresses (country_code, region_id);

create index country_regions_parent_idx
  on public.country_regions (parent_id);

alter table public.countries enable row level security;
alter table public.country_regions enable row level security;

grant select on public.countries to anon, authenticated;
grant select on public.country_regions to anon, authenticated;
grant all on public.countries to service_role;
grant all on public.country_regions to service_role;

create policy "Countries catalog read"
  on public.countries
  for select
  to anon, authenticated
  using (true);

create policy "Enabled country regions read"
  on public.country_regions
  for select
  to anon, authenticated
  using (
    is_enabled
    and exists (
      select 1
      from public.countries c
      where c.code = country_regions.country_code
        and c.is_enabled
    )
  );

comment on table public.countries is
  'Supported Arownd markets. A country is selectable only when is_enabled is true.';
comment on table public.country_regions is
  'Country-scoped administrative regions; Arabic and French names are stored in their matching columns. Algeria rows retain a link to legacy wilayas.';
comment on column public.orders.currency_code is
  'Currency snapshot for the order. Existing orders are retained as DZD; no conversion is performed.';
comment on column public.profiles.country_code is
  'Account default country. Browsing-market selection remains a separate client state.';
comment on column public.stores.country_code is
  'The single country market in which this store operates.';

commit;
